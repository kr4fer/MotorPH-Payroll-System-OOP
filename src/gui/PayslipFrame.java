package gui;

import javax.swing.*;
import java.awt.*;
import java.awt.print.*;
import java.util.Vector;

/**
 *
 * @author SunnyEljohn
 */
public class PayslipFrame extends JFrame implements Printable {

    private JPanel printPanel;

    private double parseMoney(Object value) {
        if (value == null) return 0.0;
        String cleanValue = value.toString().replace(",", "").replace("\"", "").trim();
        try {
            return Double.parseDouble(cleanValue);
        } catch (NumberFormatException e) {
            return 0.0;
        }
    }

    // Updated Constructor to accept both raw data and calculated results
    public PayslipFrame(Vector<Object> data, double gross, double sss, double philHealth,
                        double pagIbig, double withholdingTax, double netPay, String payrollPeriod) {

        setTitle("MotorPH Payslip - " + data.get(0));
        setSize(450, 700);
        setLocationRelativeTo(null);
        setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);

        printPanel = new JPanel();
        printPanel.setBackground(Color.WHITE);
        printPanel.setLayout(new BoxLayout(printPanel, BoxLayout.Y_AXIS));
        printPanel.setBorder(BorderFactory.createEmptyBorder(30, 40, 30, 40));

        // Header
        addLabel("MOTORPH OFFICIAL PAYSLIP", new Font("Segoe UI", Font.BOLD, 18));
        printPanel.add(Box.createVerticalStrut(10));

        // Employee Info
        addLabel("Employee ID: " + data.get(0));
        addLabel("Name: " + data.get(2) + " " + data.get(1));
        addLabel("Position: " + data.get(11));
        addLabel("Payroll Period: " + payrollPeriod);

        printPanel.add(Box.createVerticalStrut(10));
        printPanel.add(new JSeparator());
        printPanel.add(Box.createVerticalStrut(10));

        // Benefits / Allowances
        double rice     = parseMoney(data.get(14));
        double phone    = parseMoney(data.get(15));
        double clothing = parseMoney(data.get(16));
        double totalBenefits = rice + phone + clothing;

        addLabel("BENEFITS & ALLOWANCES", new Font("Segoe UI", Font.BOLD, 12));
        addLabel(String.format("  • Rice Subsidy:        ₱%,.2f", rice));
        addLabel(String.format("  • Phone Allowance:     ₱%,.2f", phone));
        addLabel(String.format("  • Clothing Allowance:  ₱%,.2f", clothing));
        addLabel(String.format("  • Total Benefits:      ₱%,.2f", totalBenefits));

        printPanel.add(Box.createVerticalStrut(10));

        // Earnings
        addLabel("EARNINGS", new Font("Segoe UI", Font.BOLD, 12));
        addLabel(String.format("  • Gross Salary (with benefits): ₱%,.2f", gross));

        printPanel.add(Box.createVerticalStrut(10));

        // Deductions breakdown
        double totalDeductions = sss + philHealth + pagIbig + withholdingTax;

        addLabel("DEDUCTIONS", new Font("Segoe UI", Font.BOLD, 12));
        addLabel(String.format("  • SSS:                 ₱%,.2f", sss));
        addLabel(String.format("  • PhilHealth:          ₱%,.2f", philHealth));
        addLabel(String.format("  • Pag-IBIG:            ₱%,.2f", pagIbig));
        addLabel(String.format("  • Withholding Tax:     ₱%,.2f", withholdingTax));
        addLabel(String.format("  • Total Deductions:    ₱%,.2f", totalDeductions));

        printPanel.add(Box.createVerticalStrut(15));
        printPanel.add(new JSeparator());
        printPanel.add(Box.createVerticalStrut(10));

        // Net Pay
        addLabel(String.format("NET PAY: ₱%,.2f", netPay), new Font("Segoe UI", Font.BOLD, 14));

        printPanel.add(Box.createVerticalStrut(20));

        // Footer note
        addLabel("This is an official payslip generated by the MotorPH Payroll System.",
                new Font("Segoe UI", Font.ITALIC, 10));

        // Print button
        JButton btn = new JButton("Print to PDF / Printer");
        btn.addActionListener(e -> startPrintJob());

        setLayout(new BorderLayout());
        add(new JScrollPane(printPanel), BorderLayout.CENTER);
        add(btn, BorderLayout.SOUTH);
        setVisible(true);
    }

    private void addLabel(String text) {
        addLabel(text, new Font("Segoe UI", Font.PLAIN, 12));
    }

    private void addLabel(String text, Font font) {
        JLabel l = new JLabel(text);
        l.setFont(font);
        l.setAlignmentX(Component.LEFT_ALIGNMENT);
        printPanel.add(l);
    }

    private void startPrintJob() {
        PrinterJob job = PrinterJob.getPrinterJob();
        job.setPrintable(this);
        if (job.printDialog()) {
            try {
                job.print();
            } catch (PrinterException ex) {
                ex.printStackTrace();
            }
        }
    }

    @Override
    public int print(Graphics g, PageFormat pf, int pi) {
        if (pi > 0) return NO_SUCH_PAGE;
        Graphics2D g2d = (Graphics2D) g;
        g2d.translate(pf.getImageableX(), pf.getImageableY());
        printPanel.printAll(g);
        return PAGE_EXISTS;
    }
}